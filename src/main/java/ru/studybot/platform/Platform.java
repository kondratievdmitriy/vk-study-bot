package ru.studybot.platform;
/**
 * Базовый интерфейс платформы для мессенджера/социальной сети.
 * <p>
 * Этот интерфейс служит слоем абстракции между ядром бота (класс {@link ru.studybot.bot.Bot}) 
 * и конкретной реализацией API (например, {@link ru.studybot.platform.vk.VKPlatform}).
 * </p>
 * <p>
 * Благодаря такому разделению, ядро бота ничего не знает о том, как именно 
 * отправляются сообщения или как устроен сетевой протокол. Это позволяет в будущем 
 * легко добавить поддержку другой платформы (например, Telegram или Discord), 
 * просто создав новый класс, реализующий этот интерфейс, без изменения кода самого бота.
 * </p>
 */

public interface Platform {
    void start();
    void sendMessage(long userId, String text);
}
