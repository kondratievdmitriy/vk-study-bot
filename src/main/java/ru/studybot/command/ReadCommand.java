package ru.studybot.command;

// Импортируем наши утилиты для чтения файлов и скачивания
import ru.studybot.DocumentReader;
import ru.studybot.FileDownloader;

// Импорты для работы с файлами (нужны для удаления временного файла)
import java.nio.file.Files;
import java.nio.file.Path;

/**
 * Команда /read.
 * <p>
 * Эта команда умеет делать две вещи:
 * 1. Если пользователь прикрепил файл (TXT, PDF, DOCX) — скачать его, прочитать
 *    и отправить текст обратно.
 * 2. Если пользователь просто написал текст после команды — вывести этот текст.
 * </p>
 * <p>
 * Примеры использования:
 * - /read привет мир → "📝 Вы написали: привет мир"
 * - /read + [файл.pdf] → "📄 Содержимое файла: [текст из PDF]"
 * - /read → "⚠️ Использование: /read <текст> или прикрепите файл..."
 * </p>
 */
public class ReadCommand implements Command {
    
    /**
     * Возвращает имя команды (то, что пользователь пишет после /).
     * В данном случае команда вызывается как /read.
     */
    @Override
    public String getName() { 
        return "read"; 
    }

    /**
     * Краткое описание команды для списка /help.
     */
    @Override
    public String getDescription() { 
        return "Читает текст из прикрепленного файла (TXT, PDF, DOCX) или выводит ваш текст."; 
    }

    /**
     * Подробная справка, которая показывается при /help read.
     */
    @Override
    public String getDetailedHelp() {
        return "/read <текст> — выведет ваш текст.\n"
             + "/read + прикрепленный файл — прочитает содержимое файла (TXT, PDF, DOCX).";
    }

    /**
     * Главный метод команды — здесь вся логика.
     * <p>
     * MessageContext содержит:
     * - peerId: ID пользователя или беседы
     * - args: текст после команды (например, "привет мир" в "/read привет мир")
     * - attachmentUrls: список URL прикреплённых файлов (если есть)
     * </p>
     *
     * @param context контекст сообщения со всеми данными
     * @return текст ответа, который бот отправит пользователю
     */
    @Override
    public String execute(MessageContext context) {
        // ПРОВЕРКА 1: Есть ли прикреплённые файлы?
        // context.attachmentUrls() возвращает список URL или null
        // !isEmpty() проверяет, что список не пустой
        if (context.attachmentUrls() != null && !context.attachmentUrls().isEmpty()) {
            // Берём первый файл из списка (обычно пользователь прикрепляет один)
            String fileUrl = context.attachmentUrls().get(0);
            
            try {
                // Шаг 1: Скачиваем файл из ВК во временную папку
                Path tempFile = FileDownloader.downloadFile(fileUrl);
                
                // Шаг 2: Читаем содержимое файла через наш DocumentReader
                // toString() превращает Path в строку пути
                String content = DocumentReader.readFile(tempFile.toString());
                
                // Шаг 3: Удаляем временный файл, чтобы не засорять диск
                // deleteIfExists() удаляет файл, если он существует (не падает с ошибкой, если нет)
                Files.deleteIfExists(tempFile);
                
                // Шаг 4: Форматируем и возвращаем текст
                // (обрезаем, если слишком длинный для ВК)
                return formatLongMessage(content);
                
            } catch (IllegalArgumentException e) {
                // Эта ошибка возникает, если формат файла не поддерживается
                // (например, пользователь прикрепил картинку .jpg)
                return "❌ Ошибка: " + e.getMessage();
            } catch (Exception e) {
                // Любая другая ошибка (проблемы с сетью, битый файл и т.д.)
                // Мы не показываем детали ошибки пользователю (это небезопасно)
                return "❌ Не удалось прочитать файл. Убедитесь, что это TXT, PDF или DOCX.";
            }
        }
        
        // ПРОВЕРКА 2: Если файлов нет, но есть текст после команды
        // context.args() — это всё, что написано после "/read "
        if (context.args() != null && !context.args().isBlank()) {
            // isBlank() проверяет, что строка не пустая и не состоит только из пробелов
            return "📝 Вы написали: " + context.args();
        }
        
        // ПРОВЕРКА 3: Если ни файлов, ни текста нет — показываем подсказку
        return "⚠️ Использование: /read <текст> или прикрепите файл (TXT, PDF, DOCX) к сообщению.";
    }

    /**
     * Вспомогательный метод для обрезки слишком длинных сообщений.
     * <p>
     * ВКонтакте имеет лимит на длину сообщения — около 4096 символов.
     * Если текст из файла больше, ВК просто не даст его отправить.
     * Поэтому мы обрезаем текст до 4000 символов (с запасом) и добавляем
     * пометку, что текст обрезан.
     * </p>
     *
     * @param text исходный текст из файла
     * @return отформатированный текст, готовый к отправке в ВК
     */
    private String formatLongMessage(String text) {
        // Максимальная длина сообщения (с запасом до лимита ВК в 4096)
        int maxLength = 4000;
        
        // Если текст короткий — возвращаем целиком
        if (text.length() <= maxLength) {
            return "📄 Содержимое файла:\n\n" + text.strip();
        }
        
        // Если текст длинный — обрезаем и добавляем пометку
        // substring(0, maxLength) — берём первые 4000 символов
        // strip() — убираем пробелы в начале и конце
        return "📄 Содержимое файла (обрезано, так как слишком длинное):\n\n" 
                + text.substring(0, maxLength).strip() 
                + "\n\n... (текст обрезан)";
    }
}