package ru.studybot.repository;

import ru.studybot.model.UserProgress;

import java.util.List;

/**
 * Интерфейс хранилища прогресса пользователей.
 * <p>
 * Позволяет абстрагироваться от способа хранения данных.
 * В текущей реализации используется in-memory хранилище,
 * но интерфейс готов к замене на базу данных (Задача 4).
 * </p>
 */
public interface UserProgressRepository {

    /**
     * Находит прогресс пользователя по его ID (peerId из VK).
     *
     * @param peerId идентификатор пользователя или беседы
     * @return объект прогресса, если он существует, или null, если пользователь новый
     */
    UserProgress findByPeerId(long peerId);

    /**
     * Сохраняет или обновляет прогресс пользователя (upsert).
     * <p>
     * Если пользователь уже есть в базе — его данные обновляются.
     * Если это новый пользователь — он добавляется.
     * </p>
     *
     * @param progress объект прогресса для сохранения
     */
    void save(UserProgress progress);

    /**
     * Возвращает прогресс всех пользователей (полезно для отладки или админки).
     *
     * @return список всех записей прогресса
     */
    List<UserProgress> findAll();
}